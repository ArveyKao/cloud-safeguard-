/** Operator sign-in: validates the admin token against POST /admin/login. */
import { useState } from 'react'
import { adminLogin, ApiError } from '../api/client'
import { clearToken, writeToken } from '../auth'
import { Button, CopyButton } from '../components/primitives'
import {
  IconAudit,
  IconCheck,
  IconEye,
  IconEyeOff,
  IconLeases,
  IconLock,
  IconShield,
} from '../components/icons'

interface LoginPageProps {
  onAuthenticated: (token: string) => void
}

export function LoginPage({ onAuthenticated }: LoginPageProps) {
  const [token, setToken] = useState('')
  const [revealed, setRevealed] = useState(false)
  const [submitting, setSubmitting] = useState(false)
  const [error, setError] = useState<string | null>(null)

  async function handleSubmit(event: React.FormEvent) {
    event.preventDefault()
    const candidate = token.trim()
    if (candidate === '') {
      setError('Enter the admin token generated by `csg init`.')
      return
    }
    setSubmitting(true)
    setError(null)
    // The client attaches the stored token; store the candidate for the probe,
    // then clear it on rejection so a bad token never lingers in localStorage.
    writeToken(candidate)
    try {
      const result = await adminLogin()
      if (!result.ok) throw new ApiError(401, 'unauthorized', 'Login was not accepted.')
      onAuthenticated(candidate)
    } catch (cause) {
      clearToken()
      if (cause instanceof ApiError) {
        if (cause.status === 401) {
          setError('That admin token was rejected. Check the token and try again.')
        } else if (cause.status === 0) {
          setError('Cannot reach the control plane. Is `csg serve` running on this origin?')
        } else {
          setError(cause.message)
        }
      } else {
        setError('Sign-in failed. Try again.')
      }
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <div className="login">
      <div className="login__aurora" aria-hidden="true" />
      <div className="login__grid" aria-hidden="true" />

      <section className="login__left">
        <div className="login__brand">
          <span className="login__brand-mark" aria-hidden="true">
            <IconShield size={22} />
          </span>
          <div>
            <div className="login__brand-name">Cloud Safeguard</div>
            <div className="login__brand-tag">Self-hosted credential broker</div>
          </div>
        </div>

        <div className="login__hero">
          <div className="login__eyebrow">
            <span className="status-dot status-dot--live" aria-hidden="true" />
            Operator console
          </div>
          <h1 className="login__title">
            Give agents <em>capabilities</em>,
            <br />
            not long-lived keys.
          </h1>
          <p className="login__lede">
            A control plane that mints just-in-time, least-privilege cloud credentials for AI
            agents. Every lease is scoped, time-boxed, approved when it matters, and provable in
            the audit chain.
          </p>
          <div className="login__points">
            <div className="login__point">
              <span className="login__point-icon" aria-hidden="true">
                <IconLeases size={14} />
              </span>
              <div>
                <strong>Seconds to access.</strong> Read-only work is auto-approved by policy —
                no human in the loop, no static key on disk.
              </div>
            </div>
            <div className="login__point">
              <span className="login__point-icon" aria-hidden="true">
                <IconCheck size={14} />
              </span>
              <div>
                <strong>One decision for risky work.</strong> Approve a scoped lease with a TTL and
                a reason, or deny it — the agent gets the verdict immediately.
              </div>
            </div>
            <div className="login__point">
              <span className="login__point-icon" aria-hidden="true">
                <IconAudit size={14} />
              </span>
              <div>
                <strong>Provable accountability.</strong> Every request, issuance, fetch and cloud
                call lands in a hash-chained audit log you can verify.
              </div>
            </div>
          </div>
        </div>

        <div className="login__foot">
          <span>v0.1.0</span>
          <span className="dot" aria-hidden="true" />
          <span>Loopback only</span>
          <span className="dot" aria-hidden="true" />
          <span>No cloud SDKs</span>
          <span className="dot" aria-hidden="true" />
          <span>Mock cloud included</span>
        </div>
      </section>

      <section className="login__right">
        <div className="login__card">
          <span className="login__card-mark" aria-hidden="true">
            <IconLock size={20} />
          </span>
          <h2 className="login__card-title">Operator sign-in</h2>
          <p className="login__card-sub">
            Authenticate with the admin token generated when this instance was initialised.
            It is displayed exactly once and never again.
          </p>

          <form className="login__form" onSubmit={handleSubmit} noValidate>
            <div className="field">
              <label className="field__label" htmlFor="admin-token">
                Admin token
              </label>
              <div className="login__token-row">
                <input
                  id="admin-token"
                  className="input"
                  type={revealed ? 'text' : 'password'}
                  value={token}
                  onChange={(event) => setToken(event.target.value)}
                  placeholder="csg_adm_…"
                  autoComplete="off"
                  autoCapitalize="off"
                  spellCheck={false}
                  autoFocus
                  aria-invalid={error ? 'true' : undefined}
                  aria-describedby={error ? 'login-error' : undefined}
                />
                <button
                  type="button"
                  className="btn btn--icon btn--ghost login__reveal"
                  onClick={() => setRevealed((value) => !value)}
                  aria-label={revealed ? 'Hide token' : 'Show token'}
                  title={revealed ? 'Hide token' : 'Show token'}
                >
                  {revealed ? <IconEyeOff size={16} /> : <IconEye size={16} />}
                </button>
              </div>
            </div>

            {error && (
              <div className="banner banner--error login__error" role="alert" id="login-error">
                {error}
              </div>
            )}

            <Button
              type="submit"
              variant="primary"
              size="lg"
              block
              loading={submitting}
              className="login__submit"
            >
              {submitting ? 'Verifying token…' : 'Unlock console'}
            </Button>
          </form>

          <div className="login__hint">
            <IconLock size={14} />
            <div>
              The token is stored only in this browser (<code>localStorage</code>) and sent as a
              bearer token to this origin. Find it in the output of <code>csg init</code> or the
              file passed to <code>--admin-token-file</code>. Treat it like a root credential —
              never commit or share it.
            </div>
          </div>

          <div className="login__foot" style={{ marginTop: 18, justifyContent: 'space-between' }}>
            <span>Self-hosted control plane</span>
            <CopyButton value={window.location.origin} label="Copy URL" />
          </div>
        </div>
      </section>
    </div>
  )
}
